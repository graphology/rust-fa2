use std::collections::HashMap;
use std::str::from_utf8;

use simd_csv::TotalReader;

use fa2::{FA2Data, FA2Settings};

fn les_miserables(weighted: bool) -> FA2Data<f32> {
    let data = include_bytes!("resources/les-miserables.csv");

    let mut reader = TotalReader::from_bytes(data);

    let mut data = FA2Data::new();
    let mut nodes = HashMap::<Vec<u8>, usize>::new();

    for record in reader.byte_records() {
        let source = &record[0];
        let target = &record[1];

        let source_id = *nodes
            .entry(source.to_vec())
            .or_insert_with(|| data.add_node(0.0, 0.0));

        let target_id = *nodes
            .entry(target.to_vec())
            .or_insert_with(|| data.add_node(0.0, 0.0));

        data.add_edge_with_weight(
            source_id,
            target_id,
            if weighted {
                from_utf8(&record[2]).unwrap().parse().unwrap()
            } else {
                1.0
            },
        );
    }

    data.apply_circular_layout();

    data
}

